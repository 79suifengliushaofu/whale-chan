//   主人定的是**称呼**，不是「每句话都要喊」。第一版我写成「每条都必须含主人」，
//   还被测试锁住了，结果 106 条全在开头喊一声主人——读起来像客服话术，
//   傲娇的节奏全被那个词挤掉了。正确做法是**按比例**：大约每 4 句里有 1 句带称呼，
//   而且经常出现在后半句（先嘴硬、后小声补一句「…主人」），这样才有停顿感。
//   `honorificRatio()` 和 `tsundereRatio()` 就是给这两个比例上闸门的。
