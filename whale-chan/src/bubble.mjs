/**
 * 傲娇的味道主要靠这些词：先否认、再嘴硬、找台阶下。
 * 一个库如果这类词太少，说明写着写着就变成小甜文了。
 *
 * 这里的模式要按**语法**收，别只收最显眼的「才不」。实际写起来傲娇是这些花样：
 *   否认式  才、才不是 / 才没有 / 可不是 / 又不是 / 不是啦 / 不是我的错
 *   台阶式  只是顺手 / …而已 / 顺便 / 刚好 / 随便看看 / 骗你的
 *   驱赶式  别误会 / 别催 / 别瞪 / 别笑 / 别失望 / 少得意 / 得寸进尺
 *   限量式  只准一下 / 就一下哦 / 小声一点 / 不许告诉别人
 *   反悔式  快夸我 / 当作没看见 / 没别的意思 / 我不是在撒娇
 * 只盯「才不」会漏掉一大半——上一版就是这么把 17% 当成「不够傲娇」的。
 */
const TSUNDERE =
  /哼|才[、，]?(不|没|是)|可不是|不是啦|又不是|只是|而已|顺便|刚好|随便看看|骗你的|别误会|别催|别瞪|别笑|别失望|别乱|别累|少得意|得寸进尺|谁要|谁、谁|只准|就一下|小声|不许|不准|才怪|不用哦|真的不用|快夸我|当作没看见|没别的意思|不是在撒娇|不、不|我是说|我又不|这不是|不是因为|夸我/

function hash(text) {
  let h = 0
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) | 0
  return Math.abs(h)
}

/** 所有台词拉平成一个数组（统计用）。 */
function everyLine() {
  return [...Object.values(LINES).flat(), ...Object.values(FEELINGS).flat()]
}

/** 按状态挑一句台词；seed 变化时会换一句。 */
export function pickLine(state, seed = 0) {
  const pool = LINES[state] || LINES.idle
  return pool[(seed + hash(state)) % pool.length]
}

/** 按上下文挑一句「感想」，用于表情包卡片。 */
export function pickFeeling(context, seed = 0) {
  const pool = FEELINGS[context] || FEELINGS.generic
  return pool[(seed + hash(context)) % pool.length]
}

/** 台词总条数（自检和文档要用，别再手数）。 */
export function lineTotal() {
  return Object.values(LINES).reduce((sum, pool) => sum + pool.length, 0)
}

/** 「感想」总条数。 */
export function feelingTotal() {
  return Object.values(FEELINGS).reduce((sum, pool) => sum + pool.length, 0)
}

/**
 * 带「主人」的台词占比。
 * 这是**签名称呼**，不是每句都要挂的口头禅：
 *   太低（<15%）——她不像在叫你，称呼白定了；
 *   太高（>45%）——变成客服话术，傲娇的停顿感全被那个词挤掉（第一版就是 100%）。
 * 所以自检卡的是**区间**，不是「必须全部包含」。
 */
export function honorificRatio() {
  const all = everyLine()
  if (!all.length) return 0
  return all.filter((line) => line.includes('主人')).length / all.length
}

/** 带嘴硬/否认标记的台词占比 —— 傲娇浓度的粗略代理指标。 */
export function tsundereRatio() {
  const all = everyLine()
  if (!all.length) return 0
  return all.filter((line) => TSUNDERE.test(line)).length / all.length
}

